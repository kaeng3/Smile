  assert.ok((await page.locator("#results").textContent()).startsWith(featured.events.length.toLocaleString("ko-KR")+"개 사건"));
  await page.locator("#unknown").click();
  assert.ok((await page.locator("#results").textContent()).startsWith(featured.unknown_events.length.toLocaleString("ko-KR")+"개 사건"));
  await page.locator("#all-view").click();
