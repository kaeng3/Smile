const {chromium}=require("playwright");
const assert=require("node:assert/strict");
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[];page.on("pageerror",e=>errors.push(e.message));
  const url="http://127.0.0.1:8765";
  await page.goto(url+"/");
  await page.waitForFunction(()=>document.querySelector("#heading").textContent==="장후 이브닝"||document.querySelectorAll("#toc a").length===26);
  const manifest=await page.evaluate(()=>fetch("manifest.json").then(r=>r.json()));
  assert.equal(await page.locator("#heading").textContent(),manifest.preferred_edition==="post"?"장후 이브닝":"장전 리포트");
  assert.equal(await page.locator(".masthead nav a").count(),5);
  assert.equal(await page.locator(".masthead nav a[href=\"search.html\"],.masthead nav a[href=\"history.html\"]").count(),0);
  assert.equal(await page.locator("aside #featured-nav").isVisible(),manifest.preferred_edition==="post");
  await page.locator('aside a[href="search.html#sources"]').click();
  await page.waitForURL("**/search.html#sources");
  await page.locator("#events .event button").first().waitFor({timeout:30000});
  await page.locator("#events .event button").first().click();
  await page.locator("#detail .headline").waitFor();
  await page.locator("#query").fill("zzzz-no-match-999999");
  await page.getByText("조건에 맞는 사건이 없습니다.").waitFor();
  await page.locator("#query").fill("");
  await page.locator("#source-kind").selectOption("media");
  await page.waitForFunction(()=>document.querySelector("#results").textContent.includes("사건 후보"));
  await page.locator("#source-kind").selectOption("");
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),"mobile horizontal overflow");
  await page.goto(url+"/brief.html?edition=pre");
  await page.waitForFunction(()=>document.querySelector("#heading").textContent==="장전 리포트"&&document.querySelectorAll("#toc a").length===26);
  await page.goto(url+"/editorial.html?edition=pre");
  await page.waitForFunction(()=>document.querySelectorAll("#toc a").length===26);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),"editorial mobile overflow");
  const n=await page.locator("#results").textContent();
  await page.locator("#query").fill("zzzz-no-match-999999");
  await page.getByText("검색 결과가 없습니다.",{exact:true}).waitFor();
  await page.locator("#query").fill("");
  assert.equal(await page.locator("#results").textContent(),n);
  assert.equal(await page.locator(".overview,#review-filter,#font-size,.switch").count(),0);
  assert.ok(await page.locator("#capture-summary").isVisible());
  await page.locator(".mobile-toc summary").click();
  assert.equal(await page.locator("#featured-mobile").isVisible(),false);
  await page.goto(url+"/editorial.html?edition=pre#featured-view");
  await page.waitForFunction(()=>document.querySelector("#heading").textContent==="장전 리포트"&&document.querySelectorAll("#toc a").length===26);
  await page.locator("#post").click();
  await page.waitForFunction(()=>document.querySelector("#heading").textContent==="장후 이브닝");
  await page.locator(".mobile-toc summary").click();
  await page.locator("#featured-mobile").click();
  await page.waitForFunction(()=>document.querySelectorAll("#toc a").length===1);
  assert.ok(await page.locator("#featured-note").isVisible());
  await page.locator("#toc-mobile a").first().click();
  assert.equal(await page.locator("#heading").textContent(),"[특징주] 모아보기");
  const featured=await page.evaluate(()=>fetch("editorial-post.json").then(r=>r.json()).then(d=>d.featured));
  assert.ok((await page.locator("#results").textContent()).startsWith(featured.events.length.toLocaleString("ko-KR")+"개 사건"));
  await page.locator("#post").click();
  await page.waitForFunction(()=>document.querySelector("#heading").textContent==="장후 이브닝");
  await page.locator("#market").waitFor();
  await page.route("**/scan_history.json",route=>route.fulfill({json:{"20261127":{v2:[{code:"048410",name:"현대바이오",rate:2.4,pattern:"눌림목"}]}}}));
  await page.goto(url+"/candidates.html");
  await page.locator("#chat-stocks summary").click();
  const chatStock = page.locator("#chat-stocks").getByRole("link",{name:"현대바이오 · 048410"});
  assert.ok((await chatStock.getAttribute("href")).includes("stock=048410"));
  assert.equal(await page.locator('input[type="file"], #detail, #watch-heading, main footer').count(),0);
  await page.locator("#scanner-data .scan-card").first().waitFor();
  assert.ok(await page.locator("#scanner-data .scan-card a").first().isVisible());
  await page.unroute("**/scan_history.json");
  await page.goto(url+"/history.html");
  await page.locator("#scanner-data").getByRole("searchbox").waitFor();
  assert.equal(await page.locator('input[type="file"], #compare-form').count(),0);
  const firstEvent=await page.evaluate(()=>fetch("events.json").then(r=>r.json()).then(d=>d.events[0].id));
  await page.goto(url+"/index.html?event="+encodeURIComponent(firstEvent));
  await page.waitForURL("**/search.html?event=*");
  await page.locator("#detail .headline").waitFor();
  await page.goto(url+"/themes.html");
  await page.locator("#basis").selectOption("seen");
  await page.locator("#list button").first().click({timeout:30000});
  await page.locator("#detail a").first().click();
  await page.locator("#detail .headline").waitFor();
  assert.deepEqual(errors,[]);
  console.log("Browser smoke: actual news search, briefing, scan cards, local history, mobile layout PASS");
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
