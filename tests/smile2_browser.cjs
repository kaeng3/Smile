  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),"mobile horizontal overflow");
  await page.goto(url+"/brief.html?edition=pre");
  await page.waitForFunction(()=>document.querySelector("#known").textContent!=="—");
  await page.goto(url+"/candidates.html");
  const candidate={schema:1,status:"research_candidates",as_of:"2026-11-26",errors:[],candidates:[{code:"000100",bars:[{day:"2026-11-26",open:100,high:115,low:95,close:110,volume:100,value:10500}],patterns:[{strategy:"이일홍",state:"첫 꽃 후보",first_day:"2026-11-26",today:{day:"2026-11-26",close:110},box:{upper:105,lower:90}}]}]};
